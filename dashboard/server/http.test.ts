import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createDashboard } from './server.ts';
test('HTTP accepts reports, rejects unknown Machines, and streams Usage', async t => {
  const dir = mkdtempSync(join(tmpdir(), 'hangar-http-'));
  let now = 120_001;
  const app = createDashboard({ db: join(dir, 'test.db'), machines: [{ id: 'pc', name: 'PC', os: 'windows', collector: 'wsl' }], collect: false, clock: () => now, dist: join(dir, 'missing') });
  await new Promise<void>(resolve => app.server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await app.close(); rmSync(dir, { recursive: true }); });
  const base = `http://127.0.0.1:${(app.server.address() as any).port}`;
  const abort = new AbortController(); t.after(() => abort.abort());
  const events = await fetch(base + '/api/events', { signal: abort.signal });
  const reader = events.body!.getReader(); await reader.read();
  const report = { machine: 'pc', cpu: 10, ram: { used: 3, total: 4 }, disks: [{ name: 'C:', used: 1, total: 2 }], services: { t3: true } };
  const post = (v: unknown) => fetch(base + '/api/report', { method: 'POST', body: JSON.stringify(v) });
  assert.equal((await post({ ...report, machine: 'unknown' })).status, 404);
  assert.equal((await post({ ...report, cpu: '10' })).status, 400);
  assert.equal((await fetch(base + '/api/report', { method: 'POST', body: '{' })).status, 400);
  assert.equal((await post({ ...report, at: "untrusted client clock" })).status, 204);
  const body = await (await fetch(base + '/api/machines')).json();
  assert.equal(body.now, '1970-01-01T00:02:00.001Z');
  assert.deepEqual(body.machines[0], { id: 'pc', name: 'PC', os: 'windows', online: true, lastSeen: body.now, usage: { at: body.now, cpu: 10, ram: report.ram, disks: report.disks, services: report.services }, vpns: [], history: [{ t: '1970-01-01T00:02:00.000Z', cpu: 10, ram: 75, disk: 50 }] });
  const event = new TextDecoder().decode((await reader.read()).value);
  assert.match(event, /^event: machine\ndata: /);
  const payload = JSON.parse(event.split('data: ')[1].trim());
  assert.equal(payload.online, true); assert.equal(payload.history, undefined); assert.deepEqual(payload.minute, body.machines[0].history[0]);
  now = 180_000;
  app.tick();
  assert.equal((await (await fetch(base + '/api/machines')).json()).machines[0].online, false);
  const offline = new TextDecoder().decode((await reader.read()).value);
  const offlinePayload = JSON.parse(offline.split('data: ')[1].trim());
  assert.equal(offlinePayload.online, false); assert.equal(offlinePayload.minute, null);
  assert.equal((await post({ ...report, cpu: 90 })).status, 204);
  const rollover = (await (await fetch(base + '/api/machines')).json()).machines[0];
  assert.deepEqual(rollover.history, [body.machines[0].history[0], { t: '1970-01-01T00:03:00.000Z', cpu: 90, ram: 75, disk: 50 }]);
  await reader.read();
  now = 86_520_000;
  assert.equal((await (await fetch(base + '/api/machines')).json()).machines[0].history.length, 2);
  now++;
  assert.deepEqual((await (await fetch(base + '/api/machines')).json()).machines[0].history, [{ t: '1970-01-01T00:03:00.000Z', cpu: 90, ram: 75, disk: 50 }]);
  assert.match(await (await fetch(base + '/some/page')).text(), /isn't built yet/);
  await reader.cancel();
});
test('static files have content types, SPA fallback, and cannot escape dist', async t => {
  const { mkdirSync, writeFileSync, symlinkSync } = await import('node:fs');
  const dir = mkdtempSync(join(tmpdir(), 'hangar-static-')), dist = join(dir, 'dist');
  mkdirSync(dist); mkdirSync(join(dist, 'assets')); writeFileSync(join(dist, 'assets/app.js'), 'asset'); writeFileSync(join(dist, 'index.html'), '<h1>Dashboard</h1>');
  writeFileSync(join(dist, 'app.js'), 'console.log("hello")');
  writeFileSync(join(dir, 'private.txt'), 'secret'); symlinkSync(join(dir, 'private.txt'), join(dist, 'leak.txt'));
  const app = createDashboard({ db: join(dir, 'test.db'), collect: false, dist });
  await new Promise<void>(resolve => app.server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await app.close(); rmSync(dir, { recursive: true }); });
  const base = `http://127.0.0.1:${(app.server.address() as any).port}`;
  const js = await fetch(base + '/app.js'); assert.equal(js.headers.get('content-type'), 'text/javascript');
  assert.equal(await js.text(), 'console.log("hello")');
  const page = await fetch(base + '/machines/pc'); assert.equal(page.headers.get('content-type'), 'text/html');
  assert.equal(await page.text(), '<h1>Dashboard</h1>');
  assert.equal(page.headers.get('cache-control'), 'no-cache');
  assert.equal((await fetch(base + '/index.html')).headers.get('cache-control'), 'no-cache');
  assert.equal((await fetch(base + '/assets/app.js')).headers.get('cache-control'), 'public, max-age=31536000, immutable');
  const head = await fetch(base + '/', { method: 'HEAD' }); assert.equal(head.status, 200); assert.equal(head.headers.get('content-type'), 'text/html'); assert.equal(await head.text(), '');
  assert.equal((await fetch(base + '/app.js', { method: 'HEAD' })).status, 200);
  assert.equal((await fetch(base + '/api/machines', { method: 'HEAD' })).status, 200);
  assert.equal((await fetch(base + '/assets/missing.js')).status, 404);
  assert.equal((await fetch(base + '/api/missing')).status, 404);
  assert.equal((await fetch(base + '/%2e%2e%2fprivate.txt')).status, 403);
  assert.equal((await fetch(base + '/leak.txt')).status, 403);
  rmSync(join(dist, 'index.html'));
  assert.match(await (await fetch(base + '/')).text(), /isn't built yet/);
  assert.equal((await fetch(base + '/missing.js')).status, 404);
  assert.equal(await (await fetch(base + '/assets/app.js')).text(), 'asset');
});
